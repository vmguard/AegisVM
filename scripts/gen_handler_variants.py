SPEC.update({opcode: (name, f"control_{name}") for opcode, name in CONTROL})
for opcode in range(61):
    name, expression = SPEC[opcode]
    signatures = [normalize(expression) + "|" + SHAPES[variant]
                  for variant in range(8)]
    if len(set(signatures)) != 8:
        raise SystemExit(
            f"opcode {opcode} ({name}) has duplicate variant signatures")

